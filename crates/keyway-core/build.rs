//! Module: keyway_core build script
//! Purpose: Embed every flag in data/flags/, which tools/generate_layout_labels.py chooses.
//! Created: 2026-11-09
//! Architecture: Writes the list that layout_labels includes, so a regenerated set of flags
//! needs no change to the source.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

const FLAG_EXTENSION: &str = "svg";

fn main() {
    let manifest_dir = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("set by Cargo"));
    let flags_dir = manifest_dir.join("../../data/flags");
    let output = PathBuf::from(env::var_os("OUT_DIR").expect("set by Cargo")).join("flag_files.rs");

    let mut flags: Vec<(String, PathBuf)> = fs::read_dir(&flags_dir)
        .expect("data/flags/ is readable")
        .map(|entry| entry.expect("data/flags/ is readable").path())
        .filter(|path| {
            path.extension()
                .is_some_and(|extension| extension == FLAG_EXTENSION)
        })
        .map(|path| {
            let name = path.file_stem().expect("a flag file has a name");

            (name.to_string_lossy().into_owned(), path)
        })
        .collect();
    flags.sort();

    let mut source = String::from("// Generated by keyway-core's build.rs from data/flags/.\n");
    source.push_str("pub const FLAG_FILES: &[(&str, &[u8])] = &[\n");

    for (name, path) in &flags {
        writeln!(
            source,
            "    ({name:?}, include_bytes!({:?})),",
            path.display().to_string()
        )
        .expect("writing to a string cannot fail");
    }

    source.push_str("];\n");
    fs::write(output, source).expect("OUT_DIR is writable");

    println!("cargo::rerun-if-changed={}", flags_dir.display());
}
