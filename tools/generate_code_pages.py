"""
Module: keyway.tools.generate_code_pages
Purpose: Regenerate data/code_pages/ from Python's Windows code page codecs.
Created: 2026-11-08
Architecture: Development-time only; keyway-core embeds the generated tables.
"""

from pathlib import Path

OEM_PAGES = (437, 720, 737, 775, 850, 852, 855, 857, 858, 860, 861, 862, 863, 864, 865, 866, 869)
ANSI_PAGES = (874, 1250, 1251, 1252, 1253, 1254, 1255, 1256, 1257, 1258)

BYTES_PER_PAGE = 256
CELLS_PER_ROW = 16
UNDEFINED_CELL = "----"
OUTPUT_DIR = Path(__file__).resolve().parent.parent / "data" / "code_pages"

# Windows draws OEM control bytes as these glyphs (MB_USEGLYPHCHARS), but the codecs
# return the raw controls, so the tables carry the glyphs instead.
OEM_CONTROL_GLYPHS = "☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"
OEM_DELETE_GLYPH = "⌂"
FIRST_OEM_CONTROL_BYTE = 0x01
DELETE_BYTE = 0x7F


def decode_byte(page, byte_value):
    """Return the character for one byte, or None when the page leaves it undefined."""
    if page in OEM_PAGES:
        if FIRST_OEM_CONTROL_BYTE <= byte_value < FIRST_OEM_CONTROL_BYTE + len(OEM_CONTROL_GLYPHS):
            return OEM_CONTROL_GLYPHS[byte_value - FIRST_OEM_CONTROL_BYTE]

        if byte_value == DELETE_BYTE:
            return OEM_DELETE_GLYPH

    try:
        return bytes([byte_value]).decode(f"cp{page}")
    except UnicodeDecodeError:
        return None


def render_table(page):
    """Render a page as a header and rows of hexadecimal Unicode scalar values."""
    lines = [f"# Generated by tools/generate_code_pages.py from the cp{page} codec. Do not edit."]

    for row_start in range(0, BYTES_PER_PAGE, CELLS_PER_ROW):
        cells = []

        for byte_value in range(row_start, row_start + CELLS_PER_ROW):
            character = decode_byte(page, byte_value)
            cells.append(UNDEFINED_CELL if character is None else f"{ord(character):04X}")

        lines.append(f"{row_start:02X}: {' '.join(cells)}")

    return "\n".join(lines) + "\n"


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    for page in OEM_PAGES + ANSI_PAGES:
        (OUTPUT_DIR / f"cp{page}.txt").write_text(render_table(page), encoding="utf-8")


if __name__ == "__main__":
    main()
